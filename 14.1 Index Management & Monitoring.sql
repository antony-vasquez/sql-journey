/*
────────────────────────────────────────── Fragmentations ───────────────────────────────────────────

	• Unused spaces in data pages, data pages are out of order

	• Methods: 
		○ Reorganize: Defragments leaf nodes to keep them sorted. Light
		○ Rebuild: Recreates index from the scratch. Heavy

	• Syntax: ALTER INDEX index_name ON Schema.TableName REORGANIZE/REBUILD	

	• Actions: <10% No action needed | 10%-30% Reorganize | >30% Rebuild 

*/

SELECT *
FROM sys.dm_db_index_physical_stats (DB_ID(), NULL, NULL, NULL, 'LIMITED')

SELECT 
	tbl.name AS TableName,
	idx.name AS IndexName,
	s.avg_fragmentation_in_percent,
	s.page_count
FROM sys.dm_db_index_physical_stats (DB_ID(), NULL, NULL, NULL, 'LIMITED') as s 
INNER JOIN sys.indexes idx
ON idx.object_id = s.object_id AND idx.index_id = s.index_id
INNER JOIN sys.tables tbl ON idx.object_id = tbl.object_id 
ORDER BY s.avg_fragmentation_in_percent DESC

ALTER INDEX idx_DBCustomers_CS ON Sales.DBCustomers REORGANIZE

